package main

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"os"
)

// starterConfig is the file `mirage init` writes: the minimal set of keys a
// valid configuration needs beyond the defaults (internal/config.Default
// supplies everything absent, and loading is strict — an unknown key would
// be a boot error, so the starter must name only real keys). mode "look" is
// the bottom rung of the integration ladder (I9: observe by default); the
// dashboard token is the one key Validate insists on and the one secret
// carried inline (I11).
const starterConfig = `# Mirage site configuration — generated by "mirage init".
#
# Minimal and valid as-is: every absent key keeps its documented default
# (see mirage.example.yaml for the complete annotated surface, including
# the store, budgets and connectors blocks). Loading is strict — a typo is
# a boot-time error, never a silently disabled control.

# Operating mode. "look" observes and records only: no decoys are served,
# nothing is enforced. The ladder: look -> tripwires (adds inert decoys)
# -> protect (enforcement becomes possible, still opt-in via
# enforcement.enabled).
mode: "look"

# Dashboard token. REQUIRED even on loopback; generated with crypto/rand.
# Treat it like a password — it is the one secret carried inline (I11).
dashboard_token: %q
`

// cmdInit implements `mirage init`: write the starter configuration with a
// freshly generated dashboard token, refusing to clobber an existing file
// unless --force says otherwise. The written file is loaded back through
// config.Load before init reports success — a starter that would not boot
// is a bug in the template, and failing here beats failing at `serve`.
func cmdInit(args []string) int {
	fs, help := newFlagSet("mirage init", "mirage init [--config mirage.yaml] [--force]")
	cfgPath := fs.String("config", "mirage.yaml", "configuration file to write")
	force := fs.Bool("force", false, "overwrite an existing file")
	fs, code := parseFlags(fs, help, args)
	if fs == nil {
		return code
	}
	if code := extraArgs(fs); code != exitOK {
		return code
	}

	if _, err := os.Stat(*cfgPath); err == nil && !*force {
		fmt.Fprintf(stderr, "mirage init: %s already exists (use --force to overwrite)\n", *cfgPath)
		return exitFail
	}

	token, err := generateToken()
	if err != nil {
		fmt.Fprintf(stderr, "mirage init: %v\n", err)
		return exitFail
	}
	// 0o600: the file carries the dashboard token, the one inline secret.
	if err := os.WriteFile(*cfgPath, []byte(fmt.Sprintf(starterConfig, token)), 0o600); err != nil {
		fmt.Fprintf(stderr, "mirage init: write %s: %v\n", *cfgPath, err)
		return exitFail
	}
	// The contract is a config that PASSES validation, not merely one that
	// was written; load it back the same way every other subcommand will.
	if _, err := loadConfig(*cfgPath); err != nil {
		fmt.Fprintf(stderr, "mirage init: generated configuration failed validation: %v\n", err)
		return exitFail
	}

	fmt.Fprintf(stdout, "mirage init: wrote %s\n", *cfgPath)
	fmt.Fprintf(stdout, "dashboard token: generated (64 hex chars, crypto/rand)\n")
	fmt.Fprintf(stdout, "next steps:\n")
	fmt.Fprintf(stdout, "  mirage doctor  --config %s\n", *cfgPath)
	fmt.Fprintf(stdout, "  mirage posture --config %s\n", *cfgPath)
	fmt.Fprintf(stdout, "  mirage serve   --config %s --upstream http://127.0.0.1:9000\n", *cfgPath)
	return exitOK
}

// generateToken returns a fresh 64-hex-character dashboard token: 32 bytes
// from crypto/rand, hex-encoded — the same shape mirage.example.yaml
// recommends via `openssl rand -hex 32`. A rand failure aborts init rather
// than shipping a predictable secret; there is no fallback entropy source
// that would be honest about being weaker.
func generateToken() (string, error) {
	buf := make([]byte, 32)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("read random: %w", err)
	}
	return hex.EncodeToString(buf), nil
}
